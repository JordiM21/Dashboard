/** The line for the current 3-hour slot. Stride 61 is coprime with the length, so every line shows once per cycle. */
export function pipLine(now: number = Date.now()): string {
  const slot = Math.floor(now / (3 * 3600e3));
  return PIP_LINES[(slot * 61) % PIP_LINES.length];
}
